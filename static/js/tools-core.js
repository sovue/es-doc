(function (root) {
    const safePath = value => {
        const path = value.replaceAll('\\', '/');
        if (!path || path.startsWith('/') || /[:\x00-\x1f]/.test(path)
            || path.split('/').some(part => !part || part === '.' || part === '..') || path.length > 4096) {
            throw new Error('Недопустимый путь файла.');
        }
        return path;
    };
    const accepts = (path, mode) => (mode !== 'unrpa' && /\.rpym?c$/i.test(path))
        || (mode !== 'unrpyc' && /\.rpa$/i.test(path));
    const walkEntry = async (entry, parent, add) => {
        const path = safePath(parent + entry.name);
        if (entry.isFile) {
            const file = await new Promise((resolve, reject) => entry.file(resolve, reject));
            add({ file, path });
        } else if (entry.isDirectory) {
            const reader = entry.createReader();
            while (true) {
                const batch = await new Promise((resolve, reject) => reader.readEntries(resolve, reject));
                if (!batch.length) break;
                for (const child of batch) await walkEntry(child, path + '/', add);
            }
        }
    };
    const size = bytes => {
        if (bytes < 1024) return `${bytes} Б`;
        const unit = bytes < 1024 ** 2 ? 1 : bytes < 1024 ** 3 ? 2 : 3;
        return `${(bytes / 1024 ** unit).toLocaleString('ru-RU', { maximumFractionDigits: 1 })} ${['', 'КиБ', 'МиБ', 'ГиБ'][unit]}`;
    };
    const explainWarning = message => {
        const technical = String(message);
        const source = technical.match(/^(.+?\.rpym?c):\s*([\s\S]*)$/i);
        const path = source?.[1] || '';
        const normalized = (source?.[2] || technical).replace(/\s+/g, ' ').trim();
        const version = normalized.match(/generated by ren'?py version (\d+) or below/i);
        let title, explanation;
        if (version && /targets ren'?py version 8/i.test(normalized)) {
            title = 'Файл из старой версии Ren’Py';
            explanation = `Файл декомпилирован. Он, вероятно, создан в Ren’Py ${version[1]} или более ранней версии, а инструмент рассчитан на Ren’Py 8. В восстановленном коде возможны ошибки и неточности.`;
        } else if (/unexpected slot structure/i.test(normalized)) {
            title = 'Изменённая структура файла';
            explanation = 'Файл декомпилирован, но его внутренний формат отличается от ожидаемого. В восстановленном коде возможны неточности.';
        } else if (/user-defined displayable/i.test(normalized)) {
            const style = normalized.match(/style name "([^"]*)" will be substituted/i);
            title = 'Имя элемента интерфейса восстановлено приблизительно';
            explanation = 'Код восстановлен, но имя нестандартного элемента интерфейса не сохранилось в скомпилированном файле. '
                + (style ? `Вместо него использовано имя стиля «${style[1]}». ` : 'Вместо него использовано имя стиля. ')
                + 'Сверьте имя элемента с его регистрацией через renpy.register_sl_displayable.';
        } else if (/Исходный файл .+ уже есть в архиве, сохранён без замены\./i.test(normalized)) {
            title = 'Сохранён готовый исходник';
            explanation = 'В архиве уже был исходный файл .rpy или .rpym. Он сохранён без изменений, повторная декомпиляция этого файла не выполнялась.';
        } else if (/^Attempting to deobfuscate file:/i.test(normalized)) {
            title = 'Использован расширенный способ восстановления';
            explanation = 'Файл восстановлен с помощью расширенной декомпиляции. Неудачные промежуточные попытки в техническом сообщении не означают, что вся обработка завершилась ошибкой.';
        } else {
            title = 'Результат требует проверки';
            explanation = 'Файл получен, но инструмент сообщил замечание при его обработке. Это не означает, что обработка завершилась ошибкой, в результате могут быть неточности.';
        }
        return { path, title, explanation, technical };
    };
    root.ESDocTools = { safePath, accepts, walkEntry, size, explainWarning };
})(globalThis);
