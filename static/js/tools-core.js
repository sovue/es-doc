(function (root) {
    const safePath = value => {
        const path = value.replaceAll('\\', '/');
        if (!path || path.startsWith('/') || /[:\x00-\x1f]/.test(path)
            || path.split('/').some(part => !part || part === '.' || part === '..') || path.length > 4096) {
            throw new Error('Недопустимый путь файла.');
        }
        return path;
    };
    const accepts = (path, mode) => (mode !== 'unrpa' && /\.(?:rpym?c|pyc)$/i.test(path))
        || (mode !== 'unrpyc' && /\.rpa$/i.test(path));
    const archiveName = value => {
        const name = value.trim().replace(/\.rpa$/i, '') + '.rpa';
        if (!name || name === '.rpa' || name.length > 255 || /[\\/:*?"<>|\x00-\x1f]/.test(name)
            || name.startsWith('.') || /^(con|prn|aux|nul|com[1-9]|lpt[1-9])\./i.test(name)) {
            throw new Error('Укажите имя архива без пути и символов \\ / : * ? " < > |.');
        }
        return name;
    };
    const packPath = (path, strip = '', prefix = '') => {
        path = safePath(path);
        if (strip && !path.startsWith(strip)) throw new Error('Удаляемая папка должна быть общей для всех файлов.');
        prefix = prefix.trim().replaceAll('\\', '/').replace(/\/$/, '');
        if (prefix) {
            try { prefix = safePath(prefix) + '/'; }
            catch { throw new Error('Укажите относительный путь папки без .., начального / и двоеточия. Например: my_mod.'); }
        }
        return safePath(prefix + path.slice(strip.length));
    };
    const commonFolders = paths => {
        if (!paths.length) return [];
        const parts = safePath(paths[0]).split('/');
        const folders = [];
        for (let i = 1; i < parts.length; i++) {
            const prefix = parts.slice(0, i).join('/') + '/';
            if (!paths.every(path => path.startsWith(prefix))) break;
            folders.push(prefix);
        }
        return folders;
    };
    const walkEntry = async (entry, parent, add) => {
        const path = safePath(parent + entry.name);
        if (entry.isFile) {
            const file = await new Promise((resolve, reject) => entry.file(resolve, reject));
            add({ file, path });
        } else if (entry.isDirectory) {
            const reader = entry.createReader();
            while (true) {
                const batch = await new Promise((resolve, reject) => reader.readEntries(resolve, reject));
                if (!batch.length) break;
                for (const child of batch) await walkEntry(child, path + '/', add);
            }
        }
    };
    const size = bytes => {
        if (bytes < 1024) return `${bytes} Б`;
        const unit = bytes < 1024 ** 2 ? 1 : bytes < 1024 ** 3 ? 2 : 3;
        return `${(bytes / 1024 ** unit).toLocaleString('ru-RU', { maximumFractionDigits: 1 })} ${['', 'КиБ', 'МиБ', 'ГиБ'][unit]}`;
    };
    const explainWarning = message => {
        const technical = String(message);
        const source = technical.match(/^(.+?\.(?:rpym?c|pyc)):\s*([\s\S]*)$/i)
        const path = source?.[1] || '';
        const normalized = (source?.[2] || technical).replace(/\s+/g, ' ').trim();
        const version = normalized.match(/generated by ren'?py version (\d+) or below/i);
        let title, explanation;
        if (/Контейнер: Python-блок.*байткод/i.test(normalized)) {
            title = 'Python-блок восстановлен частично';
            explanation = 'Исходный Python-код не восстановлен: в файле сохранился только байткод. На месте блока оставлены комментарий и pass. Для работы сценария этот код потребуется восстановить отдельно.';
        } else if (/Контейнер:.*не восстановлен/i.test(normalized)) {
            title = 'Не удалось раскрыть контейнер'
            explanation = 'Исходный контейнер сохранён в .rpy. Его содержимое не удалось извлечь. Остальные восстановленные блоки остаются доступны.';
        } else if (/Контейнер: восстановлено блоков:/i.test(normalized)) {
            title = 'Извлечены блоки сценария'
            explanation = 'Извлечённые блоки добавлены ниже основного сценария для чтения и адаптации. Исходные контейнеры сохранены. Загрузчик игры автоматически не переписывается.';
        } else if (version && /targets ren'?py version 8/i.test(normalized)) {
            title = "Файл из старой версии Ren'Py"
            explanation = `Файл декомпилирован. Он, вероятно, создан в Ren'Py ${version[1]} или более ранней версии, инструмент рассчитан на Ren'Py 8. В восстановленном коде возможны ошибки и неточности.`;
        } else if (/unexpected slot structure/i.test(normalized)) {
            title = 'Изменённая структура файла';
            explanation = 'Файл декомпилирован, но его внутренний формат отличается от ожидаемого. В восстановленном коде возможны неточности.';
        } else if (/user-defined displayable/i.test(normalized)) {
            const style = normalized.match(/style name "([^"]*)" will be substituted/i);
            title = 'Имя элемента интерфейса восстановлено приблизительно';
            explanation = 'Код восстановлен, но имя нестандартного элемента интерфейса не сохранилось в скомпилированном файле. '
                + (style ? `Вместо него использовано имя стиля «${style[1]}». ` : 'Вместо него использовано имя стиля. ')
                + 'Сверьте имя элемента с его регистрацией через renpy.register_sl_displayable.';
        } else if (/Исходный файл .+ уже есть в архиве, сохранён без замены\./i.test(normalized)) {
            title = 'Сохранён готовый исходник';
            explanation = 'В архиве уже был исходный файл .rpy, .rpym или .py. Он сохранён без изменений, повторная декомпиляция этого файла не выполнялась.'
        } else if (/^Attempting to deobfuscate file:/i.test(normalized)) {
            title = 'Использован расширенный способ восстановления';
            explanation = 'Файл восстановлен с помощью расширенной декомпиляции. Неудачные промежуточные попытки в техническом сообщении не означают, что вся обработка завершилась ошибкой.';
        } else {
            title = 'Результат требует проверки';
            explanation = 'Файл получен, но инструмент сообщил замечание при его обработке. Это не означает, что обработка завершилась ошибкой, в результате могут быть неточности.';
        }
        return { path, title, explanation, technical };
    };
    const explainError = (message, filename = '') => {
        const technical = String(message);
        const source = technical.match(/^(.+?\.(?:rpym?c|rpa|pyc)):\s*([\s\S]*)$/i);
        const path = filename || source?.[1] || '';
        const normalized = (source?.[2] || technical).replace(/\s+/g, ' ').trim();
        let title = 'Не удалось обработать файл';
        let explanation = 'Попробуйте открыть файл ещё раз. Если ошибка повторяется, выберите другой файл из папки игры. Техническое сообщение ниже поможет разобраться в причине.';
        let tryHarder = false;
        if (/PYC:.*Python.*не поддерживается/i.test(normalized)) {
            title = 'Версия Python не поддерживается'
            explanation = 'Декомпиляция PYC доступна для байткода Python 2.0–3.8. Этот файл создан другой версией Python. В ZIP сохранится оригинал .pyc.'
        } else if (/PYC:/i.test(normalized)) {
            title = 'Не удалось восстановить Python-файл'
            explanation = 'Файл может быть повреждён или содержать инструкции, которые декомпилятор не умеет восстанавливать. В ZIP сохранится оригинал .pyc.'
        } else if (/MemoryError|out of memory|memory access out of bounds|allocation failed/i.test(normalized)) {
            title = 'Браузеру не хватило памяти';
            explanation = 'Добавьте меньше файлов или обрабатывайте архивы по одному. Если ZIP уже готовы, их ссылки остаются доступны.';
        } else if (/Failed to fetch|NetworkError|Load failed|dynamically imported module|Не удалось загрузить инструменты/i.test(normalized)) {
            title = 'Не удалось загрузить инструменты';
            explanation = 'Проверьте соединение с сайтом и повторите действие. Файлы остаются на вашем устройстве.';
        } else if (/UnknownArchive|unsupported archive|archive.*(?:unknown|unsupported)|неподдерживаем.+архив/i.test(normalized)) {
            title = 'Не удалось распознать формат архива';
            explanation = 'Выберите оригинальный .rpa из папки игры. Изменённые или зашифрованные архивы могут не поддерживаться.';
        } else if (/BadRpyc|Invalid RPYC|right slot to load|zlib compressed blob|Incorrect Header|Broken slot/i.test(normalized)) {
            title = 'Не удалось распознать формат сценария';
            tryHarder = /header.*(?:modified|changed)|structure has been changed|Incorrect Header|Broken slot/i.test(normalized);
            explanation = 'Выберите оригинальный файл из папки игры: он может быть повреждён или иметь изменённый формат.'
                + (tryHarder ? ' Если формат был намеренно изменён, попробуйте расширенную декомпиляцию в настройках.' : '');
        } else if (/NotReadableError|NotAllowedError|permission denied|Недопустимый путь/i.test(normalized)) {
            title = 'Не удалось прочитать файл или папку';
            explanation = 'Проверьте доступ к файлам и добавьте их ещё раз. Для папки можно выбрать нужные файлы отдельно.';
        } else if (/Не удалось запустить инструменты|Браузер не поддерживает|Браузер не смог передать/i.test(normalized)) {
            title = 'Браузер не смог запустить обработку';
            explanation = 'Повторите действие с меньшим набором файлов. Если ошибка повторяется, обновите страницу или попробуйте актуальный Firefox, Chrome или Edge.';
        }
        return { path, title, explanation, technical, tryHarder };
    };
    const pluralRules = new Intl.PluralRules('ru-RU');
    const countLabel = (count, one, few, many) => {
        const category = pluralRules.select(count);
        return `${count.toLocaleString('ru-RU')} ${{ one, few, many }[category] || many}`;
    };
    root.ESDocTools = { safePath, accepts, walkEntry, size, explainWarning, explainError, countLabel,
        archiveName, packPath, commonFolders };
})(globalThis);
